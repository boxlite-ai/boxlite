//! Prepare container inputs and trusted bind-mounted files.

use boxlite_shared::errors::{BoxliteError, BoxliteResult};
use std::fs;
use std::path::Path;

/// Validate container creation inputs
pub(crate) fn validate_container_inputs(
    rootfs: &Path,
    entrypoint: &[String],
    workdir: &Path,
) -> BoxliteResult<()> {
    if rootfs.as_os_str().is_empty() {
        return Err(BoxliteError::Internal(
            "Container rootfs path cannot be empty".to_string(),
        ));
    }

    if entrypoint.is_empty() {
        return Err(BoxliteError::Internal(
            "Container entrypoint cannot be empty".to_string(),
        ));
    }

    if workdir.as_os_str().is_empty() {
        tracing::debug!("Container working directory is empty, defaulting to '/'");
    }

    Ok(())
}

/// Create /etc/hosts, /etc/hostname and /etc/resolv.conf in the bundle dir.
/// These files are bind-mounted into the container (matching Docker/containerd).
/// Written to a trusted bundle dir — never to the container rootfs.
pub(crate) fn create_container_etc_files(
    bundle_path: &Path,
    _container_id: &str,
) -> BoxliteResult<()> {
    use std::os::unix::fs::OpenOptionsExt;

    const DEFAULT_HOSTNAME: &str = "boxlite";
    const DNS_GATEWAY: &str = "192.168.127.1";
    const FILE_MODE: u32 = 0o644; // matches containerd WriteFile(path, content, 0644)

    let write_etc_file = |name: &str, content: &str| -> BoxliteResult<()> {
        let path = bundle_path.join(name);
        let mut file = fs::OpenOptions::new()
            .write(true)
            .create(true)
            .truncate(true)
            .mode(FILE_MODE)
            .open(&path)
            .map_err(|e| BoxliteError::Internal(format!("Failed to create {}: {}", name, e)))?;
        std::io::Write::write_all(&mut file, content.as_bytes())
            .map_err(|e| BoxliteError::Internal(format!("Failed to write {}: {}", name, e)))?;
        Ok(())
    };

    write_etc_file("hostname", &format!("{DEFAULT_HOSTNAME}\n"))?;

    write_etc_file(
        "hosts",
        &format!(
            "127.0.0.1\tlocalhost\n\
             ::1\t\tlocalhost ip6-localhost ip6-loopback\n\
             fe00::0\t\tip6-localnet\n\
             ff00::0\t\tip6-mcastprefix\n\
             ff02::1\t\tip6-allnodes\n\
             ff02::2\t\tip6-allrouters\n\
             127.0.1.1\t{DEFAULT_HOSTNAME}\n"
        ),
    )?;

    write_etc_file(
        "resolv.conf",
        &format!("# Generated by BoxLite\nnameserver {DNS_GATEWAY}\nsearch localdomain\n"),
    )?;

    tracing::debug!("Created /etc/hostname, /etc/hosts, /etc/resolv.conf in bundle dir");

    Ok(())
}

/// Remove bundle directory
pub(crate) fn cleanup_bundle_directory(bundle_path: &std::path::Path) {
    if let Err(e) = std::fs::remove_dir_all(bundle_path) {
        if e.kind() == std::io::ErrorKind::NotFound {
            return;
        }
        tracing::warn!(
            bundle_path = %bundle_path.display(),
            error = %e,
            "Failed to remove bundle directory"
        );
    }
}
