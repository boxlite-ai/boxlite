func TestLegacyNATNormalizationPreservesTranslation(t *testing.T) {
	const export = `# Generated by iptables-save v1.8.10 on Tue Nov 24 00:00:00 2026
*nat
:OUTPUT ACCEPT [0:0]
-A OUTPUT -d 192.0.2.1/32 -m comment --comment "pool [9:72]" -j DNAT --to-destination 192.0.2.2
COMMIT
# Completed on Tue Nov 24 00:00:00 2026
`
	before := normalizeLegacyNAT([]byte(export))
	changedCounters := strings.ReplaceAll(export, "00:00:00", "00:00:01")
	changedCounters = strings.Replace(changedCounters, "[0:0]", "[9:72]", 1)
	if after := normalizeLegacyNAT([]byte(changedCounters)); !bytes.Equal(before, after) {
		t.Fatalf("chain counters changed normalized NAT:\n%s\n%s", before, after)
	}
	changedTarget := strings.Replace(export, "192.0.2.2", "192.0.2.3", 1)
	if after := normalizeLegacyNAT([]byte(changedTarget)); bytes.Equal(before, after) {
		t.Fatal("translation target change must remain visible")
	}
	if !bytes.Contains(before, []byte(`--comment "pool [9:72]"`)) {
		t.Fatal("a counter-like string inside a rule must remain unchanged")
	}
}

func TestTopologyCommandOutputLimit(t *testing.T) {
	const limit = 1 << 20
	for _, test := range []struct {
		name string
		size int
	}{
		{"at limit", limit},
		{"one byte over", limit + 1},
	} {
		t.Run(test.name, func(t *testing.T) {
			ctx, cancel := context.WithTimeout(t.Context(), 5*time.Second)
			defer cancel()
			output, err := topologyCommand(ctx, "head", []string{"-c", strconv.Itoa(test.size), "/dev/zero"})
			if test.size > limit {
				if err == nil || output != nil || ctx.Err() != nil {
					t.Fatalf("oversized topology: got %d bytes, error %v, context %v", len(output), err, ctx.Err())
				}
				return
			}
			if err != nil || len(output) != test.size {
				t.Fatalf("topology at limit: got %d bytes, error %v", len(output), err)
			}
		})
	}
}
