// AppliedTopology reads the running route policy and both kernel NAT frontends.
// The operator's inventory supplies protected coverage and pins this digest.
func AppliedTopology(ctx context.Context) (string, error) {
	queries := []struct {
		program string
		args    []string
	}{
		{"ip", []string{"-json", "-4", "route", "show", "table", "all"}},
		{"ip", []string{"-json", "-6", "route", "show", "table", "all"}},
		{"ip", []string{"-json", "-4", "rule", "show"}},
		{"ip", []string{"-json", "-6", "rule", "show"}},
		{"nft", []string{"-j", "list", "ruleset"}},
		{"iptables-legacy-save", []string{"-t", "nat"}},
		{"ip6tables-legacy-save", []string{"-t", "nat"}},
	}
	h := sha256.New()
	_, _ = h.Write([]byte("boxlite applied Cloud topology v2\n"))
	for i, query := range queries {
		output, err := topologyCommand(ctx, query.program, query.args)
		if err != nil {
			return "", err
		}
		if i == 1 && !hasIPv6Uplink(output) {
			return "", fmt.Errorf("Cloud topology has no IPv6 default route with an active global unicast interface")
		}
		if i >= 5 {
			output = normalizeLegacyNAT(output)
		} else {
			output, err = normalizeTopologyJSON(output, i < 2)
			if err != nil {
				return "", fmt.Errorf("invalid JSON from Cloud topology query %s: %w", query.program, err)
			}
		}
		_, _ = fmt.Fprintf(h, "%d\n", len(output))
		_, _ = h.Write(output)
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}

var legacyNATChainCounters = regexp.MustCompile(`(?m)^(:\S+ \S+ )\[[0-9]+:[0-9]+\]$`)

func normalizeLegacyNAT(output []byte) []byte {
	var stable bytes.Buffer
	for _, line := range bytes.Split(output, []byte{'\n'}) {
		if bytes.HasPrefix(line, []byte("# Generated by ")) || bytes.HasPrefix(line, []byte("# Completed on ")) {
			continue
		}
		_, _ = stable.Write(line)
		_ = stable.WriteByte('\n')
	}
	// Both legacy exporters print live built-in chain counters without -c.
	return legacyNATChainCounters.ReplaceAll(stable.Bytes(), []byte(`${1}[0:0]`))
}

func topologyCommand(ctx context.Context, program string, args []string) ([]byte, error) {
	// Never resolve a host authority through an environment-provided PATH.
	var path string
	for _, directory := range []string{"/usr/sbin/", "/sbin/", "/usr/bin/", "/bin/"} {
		if info, err := os.Stat(directory + program); err == nil {
			if stat, ok := info.Sys().(*syscall.Stat_t); ok && stat.Uid == 0 &&
				info.Mode().IsRegular() && info.Mode().Perm()&0o022 == 0 {
				path = directory + program
				break
			}
		}
	}
	if path == "" {
		return nil, fmt.Errorf("Cloud topology requires %s in a system directory", program)
	}
	var output limitedTopologyOutput
	command := exec.CommandContext(ctx, path, args...)
	command.Env = []string{"LC_ALL=C", "PATH=/usr/sbin:/sbin:/usr/bin:/bin"}
	command.Stdout = &output
	if err := command.Run(); err != nil {
		return nil, fmt.Errorf("read applied Cloud topology with %s: %w", program, err)
	}
	return output.buffer.Bytes(), nil
}

type limitedTopologyOutput struct {
	buffer bytes.Buffer
}

func (b *limitedTopologyOutput) Write(data []byte) (int, error) {
	const limit = 1 << 20
	if len(data) > limit-b.buffer.Len() {
		return 0, io.ErrShortWrite
	}
	return b.buffer.Write(data)
}

func hasIPv6Uplink(output []byte) bool {
	var routes []struct {
		Destination string `json:"dst"`
		Interface   string `json:"dev"`
		Type        string `json:"type"`
	}
	if json.Unmarshal(output, &routes) != nil {
		return false
	}
	for _, route := range routes {
		if route.Destination != "default" || (route.Type != "" && route.Type != "unicast") {
			continue
		}
		iface, err := net.InterfaceByName(route.Interface)
		if err != nil || iface.Flags&net.FlagUp == 0 || iface.Flags&net.FlagLoopback != 0 {
			continue
		}
		addresses, err := iface.Addrs()
		if err != nil {
			continue
		}
		public := netip.MustParsePrefix("2000::/3")
		for _, address := range addresses {
			ip, err := netip.ParseAddr(strings.SplitN(address.String(), "/", 2)[0])
			if err == nil && public.Contains(ip) {
				return true
			}
		}
	}
	return false
}
